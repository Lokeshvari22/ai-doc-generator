#  Complexity table
# ─────────────────────────────────────────────────────────────────────────────

def add_complexity_table(doc: Document, complexities: list):
    if not complexities:
        return
    doc.add_heading("📊 Complexity Analysis", level=2)
    table = doc.add_table(rows=1, cols=6)   # added Params column
    table.style = "Table Grid"

    hdr = table.rows[0].cells
    for i, h in enumerate(["Function", "Score", "Level", "Lines", "Params", "Recursive"]):
        hdr[i].text = h
        for run in hdr[i].paragraphs[0].runs:
            run.bold = True
            run.font.color.rgb = RGBColor(0x22, 0x22, 0x55)
        # Header shading
        tc   = hdr[i]._tc
        tcPr = tc.get_or_add_tcPr()
        shd  = OxmlElement("w:shd")
        shd.set(qn("w:val"),   "clear")
        shd.set(qn("w:color"), "auto")
        shd.set(qn("w:fill"),  "E8E8F4")
        tcPr.append(shd)
        _set_cell_border(hdr[i])

    for c in complexities:
        row = table.add_row().cells
        row[0].text = c.name
        row[1].text = str(c.score)
        row[2].text = c.level
        row[3].text = str(c.lines)
        row[4].text = str(c.params) if hasattr(c, "params") else "—"
        row[5].text = "Yes" if c.has_recursion else "No"

        # Colour row by complexity level — match emoji prefix from complexity.py
        level_lower = c.level.lower()
        if "low" in level_lower:
            fill = "E2EFDA"   # green
        elif "medium" in level_lower:
            fill = "FFF2CC"   # amber
        else:
            fill = "FFE0E0"   # red

        for cell in row:
            _set_cell_border(cell)
            tc   = cell._tc
            tcPr = tc.get_or_add_tcPr()
            shd  = OxmlElement("w:shd")
            shd.set(qn("w:val"),   "clear")
            shd.set(qn("w:color"), "auto")
            shd.set(qn("w:fill"),  fill)
            tcPr.append(shd)

    doc.add_paragraph()   # spacing after table


# ─────────────────────────────────────────────────────────────────────────────
#  Architecture diagram — P5: try/except + text fallback
# ─────────────────────────────────────────────────────────────────────────────

def add_architecture(doc: Document, img_path: str, file_analyses: dict = None):
    """
    P5: Add architecture diagram. If image unavailable, insert text dependency table.
    file_analyses: optional dict of {filename: {imports, classes, functions}}
    for building the fallback text table.
    """
    doc.add_page_break()
    doc.add_heading("🏗️ Architecture Diagram", level=1)

    try:
        if img_path and __import__("os").path.exists(img_path):
            doc.add_picture(img_path, width=Inches(6))
            p = doc.add_paragraph()
            p.add_run("Figure: Cross-file dependency and call graph.").italic = True
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            return
    except Exception as e:
        print(f"    ⚠ Diagram image failed: {e} — adding text fallback")

    # P5: Text fallback — dependency table
    doc.add_paragraph(
        "Architecture diagram could not be rendered. "
        "Dependency summary below:"
    ).italic = True

    if file_analyses:
        table = doc.add_table(rows=1, cols=3)
        table.style = "Table Grid"
        hdr = table.rows[0].cells
        for i, h in enumerate(["File", "Imports", "Functions"]):
            hdr[i].text = h
            for run in hdr[i].paragraphs[0].runs:
                run.bold = True
            _set_cell_border(hdr[i])

        for fname, info in file_analyses.items():
            row = table.add_row().cells
            row[0].text = fname
            row[1].text = ", ".join(sorted(info.get("imports", [])))[:80]
            row[2].text = ", ".join(
                f.get("name", "") for f in info.get("functions", [])
            )[:80]
            for cell in row:
                _set_cell_border(cell)
    else:
        doc.add_paragraph("No dependency data available.")


