def create_doc(project_name: str = "Project") -> Document:
    doc = Document()

    # Set narrow margins for more content per page
    for section in doc.sections:
        section.top_margin    = Inches(0.9)
        section.bottom_margin = Inches(0.9)
        section.left_margin   = Inches(1.0)
        section.right_margin  = Inches(1.0)

    # Title page
    title = doc.add_heading(f"AI Code Documentation — {project_name}", 0)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER

    sub = doc.add_paragraph(
        "Generated by AI-powered multi-model pipeline "
        "(Groq → GPT-4o → gpt-4o-mini + Phi-4)"
    )
    sub.alignment = WD_ALIGN_PARAGRAPH.CENTER
    sub.runs[0].italic = True

    doc.add_page_break()

    # P7: Add page border to document
    _add_page_border(doc)

    return doc


def _add_page_border(doc: Document):
    """P7: Add a thin single-line border around every page via sectPr XML."""
    for section in doc.sections:
        sectPr = section._sectPr
        pgBorders = OxmlElement("w:pgBorders")
        pgBorders.set(qn("w:offsetFrom"), "page")
        for side in ("top", "left", "bottom", "right"):
            border = OxmlElement(f"w:{side}")
            border.set(qn("w:val"),   "single")
            border.set(qn("w:sz"),    "6")       # 0.75pt
            border.set(qn("w:space"), "24")
            border.set(qn("w:color"), "4A4A6A")
            pgBorders.append(border)
        sectPr.append(pgBorders)


