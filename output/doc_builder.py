def save_doc(doc: Document, path: str) -> bool:
    for i in range(3):
        try:
            doc.save(path)
            print(f"  ✅ Saved: {path}")
            return True
        except PermissionError:
            print(f"  File busy, retry {i+1}/3...")
            time.sleep(2)
    return False