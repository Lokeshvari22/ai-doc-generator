def add_summary(doc: Document, summary: str):
    """
    P6: Add project summary section. Routes through _add_markdown() so that
    ### headings, **bold**, and * bullets are rendered properly in Word,
    not printed as raw markdown symbols.
    """
    doc.add_page_break()
    doc.add_heading("📋 Project Summary", level=1)
    # P6 FIX: was doc.add_paragraph(summary) — now goes through renderer
    _add_markdown(doc, summary)


